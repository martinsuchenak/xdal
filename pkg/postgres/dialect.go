package postgres

import (
	"fmt"

	"github.com/martinsuchenak/xdal/pkg/xdal"
)

type postgresDialect struct {
	*xdal.BaseDialect
}

func (d *postgresDialect) StringAggExpr(col, sep string) string {
	return fmt.Sprintf("STRING_AGG(%s, %s)", col, sep)
}

func (d *postgresDialect) RandExpr() string { return "RANDOM()" }

// NewDialect returns a Dialect configured for PostgreSQL.
func NewDialect() xdal.Dialect {
	b := &xdal.BaseDialect{
		DialectName: xdal.DialectPostgres,
		Caps: xdal.Capabilities{
			Upsert:           true,
			RowLocks:         true,
			SkipLocked:       true,
			TransactionalDDL: true,
			SharedAppLocks:   true,
		},
		UpsertStyle: xdal.OnConflictUpsert,
		LockStyle:   xdal.ForUpdateLocks,
		AppLocker:   xdal.PostgresAdvisoryLocker{},
		Placeholder: xdal.DollarPlaceholder,
		AppendLimit: xdal.LimitOffset,
		QuoteStyle:  xdal.DoubleQuoteQuoting,
	}
	b.AppendReturning = b.WriteReturning
	d := &postgresDialect{BaseDialect: b}
	b.DDL = xdal.DDLOptions{
		Types: xdal.TypeMap{
			String:        "VARCHAR(%d)",
			Text:          "TEXT",
			Integer:       "INTEGER",
			BigInteger:    "BIGINT",
			Boolean:       "BOOLEAN",
			Float:         "DOUBLE PRECISION",
			Decimal:       "NUMERIC(%d,%d)",
			Timestamp:     "TIMESTAMPTZ",
			Date:          "DATE",
			UUID:          "UUID",
			JSON:          "JSONB",
			Binary:        "BYTEA",
			Blob:          "BYTEA",
			AutoIncrement: "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
		},
		DefaultNow:        "CURRENT_TIMESTAMP",
		BoolLiteral:       d.BoolLiteral,
		AddColumnKeyword:  "ADD COLUMN",
		TableIfNotExists:  xdal.IfNotExistsClause,
		IndexIfNotExists:  xdal.IfNotExistsClause,
		DropIndexIfExists: true,
		Rename:            xdal.RenameAlterTable,
	}
	return d
}
